function add(token,kind,colour,opacity=100,variant=''){
 const role=roles[colour.toLowerCase()];
 if(!role){
  // Semantic/custom backgrounds keep their original fill and own readable foreground.
  if(kind==='bg'&&opacity>=60&&!variant){const fg=foregroundFor(colour);rules.set(token,`[data-club-theme] .${esc(token)} { --club-context-text: ${fg}; --club-context-muted: ${fg}; --club-context-accent: ${fg}; }`);}
  return;
 }
 let variable=role==='ink'?'text':role==='muted'?'muted-text':role==='dark'?'primary-hover':role;
 if(kind==='text')variable=role==='accent'?'context-accent':role==='muted'?'context-muted':'context-text';
 if(kind==='bg'&&(role==='ink'||role==='muted'))variable=role==='ink'?'primary':'soft';
 if(['border','ring','outline','decoration'].includes(kind))variable=role==='accent'?'accent':role==='primary'||role==='ink'||role==='dark'?'primary':'border';
 const v=`var(--club-${variable}${variable==='context-text'?', var(--club-text)':variable==='context-muted'?', var(--club-muted-text)':variable==='context-accent'?', var(--club-accent-text)':''})`;
 const value=opacity===100?v:`color-mix(in srgb, ${v} ${opacity}%, transparent)`;
 const prop={bg:'background-color',text:'color',border:'border-color',ring:'--tw-ring-color',outline:'outline-color',decoration:'text-decoration-color',fill:'fill',stroke:'stroke',from:'--tw-gradient-from',to:'--tw-gradient-to',via:'--tw-gradient-via'}[kind];
 if(!prop)return;
 let declarations=`${prop}: ${value} !important;`;
 if(kind==='bg'){
  const brand=['primary','ink','dark'].includes(role)&&opacity>=60,accent=role==='accent'&&opacity>=60;
  const foreground=brand?'var(--club-on-primary)':accent?'var(--club-on-accent)':'var(--club-text)';
  declarations+=` --club-context-text: ${foreground}; --club-context-muted: ${brand||accent?foreground:'var(--club-muted-text)'}; --club-context-accent: ${brand||accent?foreground:'var(--club-accent-text)'}; color: ${foreground};`;
 }
 const pseudo=variant==='hover'?':hover':variant==='focus'?':focus':variant==='focus-visible'?':focus-visible':'';
 if(variant&&!pseudo)return;
 rules.set(token,`[data-club-theme] .${esc(token)}${pseudo} { ${declarations} }`);
}
async function scan(directory){
 for(const entry of await readdir(directory,{withFileTypes:true})){
  const path=directory+'/'+entry.name;
  if(entry.isDirectory())await scan(path);
  else if(/\.(tsx|ts)$/.test(entry.name)){
   const source=await readFile(path,'utf8');
   for(const m of source.matchAll(/((?:(?:hover|focus|focus-visible):)?!?)(bg|text|border|ring|outline|decoration|fill|stroke|from|to|via)-\[(#[0-9a-fA-F]{6})\](?:\/(\d+))?/g)){
    const variant=m[1].replace('!','').replace(':','');add(m[0],m[2],m[3],m[4]?Number(m[4]):100,variant);
   }
  }
 }
}
